/**
 * Generate Lucide icon catalog for the picker.
 *
 * After upgrading lucide-react, re-run:
 *   pnpm run generate:icon-catalog
 *
 * Outputs:
 *   - resources/js/lib/icon-catalog.ts
 *   - storage/app/lucide-icon-keys.json
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { categoriesForIcon } from './icon-categories.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const require = createRequire(import.meta.url);

/** Custom display labels that differ from title-cased kebab keys. */
const LABEL_OVERRIDES = {
    'wand-sparkles': 'AI writing',
};

function titleCaseKey(key) {
    return key
        .split('-')
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join(' ');
}

function resolveDynamicImportsPath() {
    const packageJsonPath = require.resolve('lucide-react/package.json');

    return path.join(
        path.dirname(packageJsonPath),
        'dist',
        'esm',
        'dynamicIconImports.js',
    );
}

function extractIconKeys(source) {
    const keys = new Set();
    const pattern = /["']([a-z0-9-]+)["']\s*:/g;
    let match;

    while ((match = pattern.exec(source)) !== null) {
        keys.add(match[1]);
    }

    return [...keys].sort((a, b) => a.localeCompare(b));
}

async function main() {
    const importsPath = resolveDynamicImportsPath();
    const source = await readFile(importsPath, 'utf8');
    const keys = extractIconKeys(source);

    if (keys.length === 0) {
        throw new Error(
            `No icon keys found in ${importsPath}. Lucide layout may have changed.`,
        );
    }

    const categorySet = new Set();

    const options = keys.map((key) => {
        const label = LABEL_OVERRIDES[key] ?? titleCaseKey(key);
        const categories = categoriesForIcon(key, label);
        const searchText = `${key} ${label} ${categories.join(' ')}`.toLowerCase();

        for (const category of categories) {
            categorySet.add(category);
        }

        return { key, label, searchText, categories };
    });

    const categories = [...categorySet].sort((a, b) => a.localeCompare(b));

    const outDir = path.join(root, 'resources', 'js', 'lib');
    const outFile = path.join(outDir, 'icon-catalog.ts');
    const keysDir = path.join(root, 'storage', 'app');
    const keysFile = path.join(keysDir, 'lucide-icon-keys.json');

    await mkdir(outDir, { recursive: true });
    await mkdir(keysDir, { recursive: true });

    const header = `/** Generated by scripts/generate-icon-catalog.mjs — do not edit manually. Run \`pnpm run generate:icon-catalog\` after Lucide upgrades. */\n`;
    const body = `export const ICON_OPTIONS = ${JSON.stringify(options, null, 4)} as const;\n\nexport const ICON_CATEGORIES = ${JSON.stringify(categories, null, 4)} as const;\n\nexport type IconKey = (typeof ICON_OPTIONS)[number]['key'];\n\nexport type IconOption = (typeof ICON_OPTIONS)[number];\n\nexport type IconCategory = (typeof ICON_CATEGORIES)[number];\n\nexport const ICON_KEYS = new Set<string>(\n    ICON_OPTIONS.map((option) => option.key),\n);\n`;

    await writeFile(outFile, header + body, 'utf8');
    await writeFile(keysFile, `${JSON.stringify(keys, null, 4)}\n`, 'utf8');

    console.log(
        `Wrote ${options.length} icons (${categories.length} categories) to ${path.relative(root, outFile)}`,
    );
    console.log(`Wrote ${keys.length} keys to ${path.relative(root, keysFile)}`);
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});
